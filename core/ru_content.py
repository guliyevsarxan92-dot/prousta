def translate_ru_query(query: str) -> str:
    """Translates Russian search queries into Azerbaijani service/location tokens for search_listings."""
    if not query:
        return query
    lowered = query.lower().replace('ё', 'е')
    if not any('а' <= ch <= 'я' for ch in lowered):
        return query
    import re
    mapped = []
    for ru_stem, az_term in RU_QUERY_SYNONYMS.items():
        if ru_stem in lowered:
            mapped.append(az_term)
    latin_tokens = re.findall(r'[a-zA-Z0-9əƏıİöÖüÜçÇşŞğĞ]+', query)
    if mapped:
        return ' '.join([*latin_tokens, *dict.fromkeys(mapped)])
    return query


def category_name_ru(category) -> str:
    if category is None:
        return ''
    slug = category if isinstance(category, str) else getattr(category, 'slug', '')
    fallback = '' if isinstance(category, str) else getattr(category, 'ad', '')
    return CATEGORIES_RU.get(slug, fallback)


def location_ru(slug: str):
    from .locations import LOKASIYALAR
    if not slug or slug not in LOKASIYALAR:
        return None
    base = dict(LOKASIYALAR[slug])
    ru = LOKASIYALAR_RU.get(slug)
    if ru:
        base.update(ru)
    else:
        base['locative'] = f'в {base["ad"]}'
    return base


def priority_page_ru(page):
    if not page:
        return None
    slug = page.get('slug')
    ru = PRIORITY_PAGES_RU.get(slug)
    if not ru:
        return page
    merged = dict(page)
    merged.update(ru)
    merged['url'] = f'/ru/xidmet/{slug}/'
    return merged


